SELECT e.id_especie, c.raza
FROM vetclinic_catalogo_razas c
JOIN especies e ON e.nombre_especie = c.especie
WHERE NOT EXISTS (
    SELECT 1 FROM razas r WHERE r.id_especie = e.id_especie AND r.nombre_raza = c.raza
);
